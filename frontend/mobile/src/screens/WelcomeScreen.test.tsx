import { AppState, ScrollView, type AppStateStatus } from 'react-native'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react-native'
import { colors } from '../ui'
import { WelcomeScreen } from './WelcomeScreen'

const swipe = (x: number) => {
  const carousel = screen.getByTestId('welcome-carousel')
  fireEvent(carousel, 'scrollBeginDrag')
  fireEvent(carousel, 'scrollEndDrag')
  fireEvent(carousel, 'momentumScrollBegin')
  fireEvent(carousel, 'momentumScrollEnd', { nativeEvent: { contentOffset: { x } } })
}
const layout = (width: number) => fireEvent(screen.getByTestId('welcome-carousel'), 'layout', { nativeEvent: { layout: { width } } })
const advance = (milliseconds: number) => act(() => { jest.advanceTimersByTime(milliseconds) })
const actions = () => ({ busy: false, error: null, onSignup: jest.fn(), onLogin: jest.fn(), onBrowse: jest.fn() })
const previousAppState = AppState.currentState

beforeEach(() => {
  AppState.currentState = 'active'
  jest.useFakeTimers().setSystemTime(new Date('2026-10-02T03:00:00Z'))
})
afterEach(() => { cleanup(); AppState.currentState = previousAppState; jest.restoreAllMocks(); jest.useRealTimers() })

test('four introduction previews keep the actual card vocabulary and authentication actions', () => {
  const props = actions()
  render(<WelcomeScreen {...props} />)
  layout(360)
  expect(screen.getByText('이 조건으로 검색할까요?')).toBeTruthy()
  expect(screen.queryByRole('button', { name: '이 조건으로 검색' })).toBeNull()
  swipe(360)
  expect(screen.getByText('2026 스마트공장 고도화 지원사업 2차')).toBeTruthy()
  expect(screen.getByText('청년일자리 도약장려금 하반기')).toBeTruthy()
  expect(screen.getAllByTestId('program-status-dot')).toHaveLength(2)
  expect(screen.getByText('D-5')).toBeTruthy()
  expect(screen.getByText('D-3')).toBeTruthy()
  expect(screen.getByText('조건 확인')).toHaveStyle({ backgroundColor: colors.soft })
  expect(screen.getByText('확인 필요')).toHaveStyle({ backgroundColor: colors.warningSoft })
  swipe(720)
  expect(screen.getByText('원문 근거 답변 · 예시')).toBeTruthy()
  swipe(1080)
  expect(screen.getByText('사업계획서_초안_v4.hwpx')).toBeTruthy()
  fireEvent.press(screen.getByLabelText('회원가입하고 시작하기'))
  fireEvent.press(screen.getByLabelText('이미 계정이 있습니다'))
  fireEvent.press(screen.getByLabelText('로그인 없이 둘러보기'))
  expect(props.onSignup).toHaveBeenCalledTimes(1)
  expect(props.onLogin).toHaveBeenCalledTimes(1)
  expect(props.onBrowse).toHaveBeenCalledTimes(1)
})

test('only horizontal swipes navigate manually and first/last limits do not trigger entry', () => {
  const props = actions()
  render(<WelcomeScreen {...props} />)
  layout(360)
  expect(screen.getByTestId('welcome-carousel').props.horizontal).toBe(true)
  expect(screen.getByTestId('welcome-carousel').props.pagingEnabled).toBe(true)
  expect(screen.getAllByRole('button').map(button => button.props.accessibilityLabel)).toEqual([
    '회원가입하고 시작하기', '이미 계정이 있습니다', '로그인 없이 둘러보기',
  ])
  for (const label of ['건너뛰기', '이전', '다음', '둘러보기', '온보딩 4장 보기']) {
    expect(screen.queryByLabelText(label)).toBeNull()
  }
  swipe(360)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  swipe(0)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  swipe(-100)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  swipe(1600)
  expect(screen.getByText('4 / 4')).toBeTruthy()
  expect(props.onBrowse).not.toHaveBeenCalled()
})

test('automatically slides after one second and waits on the last page without marking entry', () => {
  const props = actions()
  const scrollTo = jest.spyOn(ScrollView.prototype, 'scrollTo')
  render(<WelcomeScreen {...props} />)
  layout(360)
  advance(999)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  advance(1)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  expect(screen.getByText('공고 원문 문장으로 확인해요')).toBeTruthy()
  expect(screen.queryByText('맞는 지원사업을 찾아요')).toBeNull()
  expect(scrollTo).toHaveBeenLastCalledWith({ x: 360, animated: true })
  advance(1000)
  expect(screen.getByText('3 / 4')).toBeTruthy()
  advance(1000)
  expect(screen.getByText('4 / 4')).toBeTruthy()
  advance(20000)
  expect(screen.getByText('4 / 4')).toBeTruthy()
  expect(props.onBrowse).not.toHaveBeenCalled()
  expect(props.onLogin).not.toHaveBeenCalled()
  expect(props.onSignup).not.toHaveBeenCalled()
})

test('swiping restarts the full delay and dragging pauses automatic movement', () => {
  render(<WelcomeScreen {...actions()} />)
  layout(360)
  advance(800)
  fireEvent(screen.getByTestId('welcome-carousel'), 'scrollBeginDrag')
  advance(10000)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  swipe(360)
  advance(999)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  advance(1)
  expect(screen.getByText('3 / 4')).toBeTruthy()
  // A cancelled swipe that settles on the same page also starts a fresh delay.
  advance(800)
  swipe(720)
  advance(999)
  expect(screen.getByText('3 / 4')).toBeTruthy()
  advance(1)
  expect(screen.getByText('4 / 4')).toBeTruthy()
  swipe(360)
  advance(1000)
  expect(screen.getByText('3 / 4')).toBeTruthy()
})

