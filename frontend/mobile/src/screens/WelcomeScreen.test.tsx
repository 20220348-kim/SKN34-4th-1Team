test('busy entry blocks automatic, swipe and account actions, then restores interaction after an error', () => {
  const props = actions()
  const view = render(<WelcomeScreen {...props} />)
  layout(360)
  swipe(360)
  view.rerender(<WelcomeScreen {...props} busy />)
  advance(10000)
  swipe(1080)
  for (const label of ['회원가입하고 시작하기', '이미 계정이 있습니다', '로그인 없이 둘러보기']) {
    fireEvent.press(screen.getByLabelText(label))
  }
  expect(screen.getByText('2 / 4')).toBeTruthy()
  expect(screen.getByTestId('welcome-carousel').props.scrollEnabled).toBe(false)
  expect(props.onBrowse).not.toHaveBeenCalled()
  expect(props.onLogin).not.toHaveBeenCalled()
  expect(props.onSignup).not.toHaveBeenCalled()
  view.rerender(<WelcomeScreen {...props} error="소개 기록 저장 실패" />)
  expect(screen.getByText('소개 기록 저장 실패')).toBeTruthy()
  advance(999)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  advance(1)
  expect(screen.getByText('3 / 4')).toBeTruthy()
  fireEvent.press(screen.getByLabelText('로그인 없이 둘러보기'))
  expect(props.onBrowse).toHaveBeenCalledTimes(1)
})

test('backgrounding and authentication pause automatic movement and unmount clears the timer', () => {
  const addListener = jest.spyOn(AppState, 'addEventListener')
  const props = actions()
  const view = render(<WelcomeScreen {...props} />)
  const onStateChange = addListener.mock.calls.find(([event]) => event === 'change')![1] as (state: AppStateStatus) => void
  advance(800)
  act(() => onStateChange('background'))
  advance(10000)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  act(() => onStateChange('active'))
  advance(999)
  expect(screen.getByText('1 / 4')).toBeTruthy()
  advance(1)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  view.rerender(<WelcomeScreen {...props} autoAdvancePaused />)
  advance(10000)
  expect(screen.getByText('2 / 4')).toBeTruthy()
  view.rerender(<WelcomeScreen {...props} />)
  advance(1000)
  expect(screen.getByText('3 / 4')).toBeTruthy()
  const remove = jest.spyOn(addListener.mock.results[0].value, 'remove')
  expect(jest.getTimerCount()).toBe(1)
  view.unmount()
  expect(remove).toHaveBeenCalledTimes(1)
  expect(jest.getTimerCount()).toBe(0)
})
